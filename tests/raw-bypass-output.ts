import { Packet, stick } from '../src/shared/profile'
const check = (name: string, ok: boolean): void => { if (!ok) throw new Error(name); console.log(name) }
const before = Uint8Array.from({ length: 36 }, (_, i) => (i * 7 + 3) & 255)
const p = new Packet(before.slice())
stick.setEnabled(p, false)
check('Raw bypass preserves every byte except processing enable', p.bytes.every((v, i) => v === (i === 0 ? before[i] & ~1 : before[i])))
check('Raw bypass reads disabled', !stick.enabled(p))
stick.setEnabled(p, true)
check('Leaving bypass restores the original tuning', p.bytes.every((v, i) => v === before[i]))
stick.applyRawLinear(p)
check('Linear 1:1 remains enabled and recognized', stick.enabled(p) && stick.isRawLinear(p))
const left = new Packet(before.slice()), right = new Packet(before.slice())
stick.setMapIndex(left, 4); stick.setMapIndex(right, 4)
const leftBefore = left.bytes.slice(), rightBefore = right.bytes.slice()
check('Unlocked sticks stay unchanged', !stick.lockStickOutput([left, right], [false, false]))
check('Lock repairs mouse output', stick.lockStickOutput([left, right], [true, false]) && stick.mapIndex(left) === 1 && stick.mapIndex(right) === 4)
const changed = Array.from(left.bytes).map((v, i) => v !== leftBefore[i] ? i : -1).filter(i => i >= 0)
check('Output lock only changes the destination byte', changed.length === 1 && right.bytes.every((v, i) => v === rightBefore[i]))
check('Lock is idempotent', !stick.lockStickOutput([left, right], [true, false]))
