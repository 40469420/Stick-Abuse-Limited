import assert from 'node:assert/strict'
import { Packet, motion, stick, parseProfile, serializeProfile } from '../src/shared/profile'
import { setCustomCurve, setHair, setMotionActivation, setWindow } from '../src/shared/tuning'
import { calibrateParts } from '../src/shared/protocol'

const p = new Packet(new Uint8Array(41).fill(0xa0))
motion.setOrientation(p, 2)
assert.equal(p.u8(4), 0xa3)
assert.equal(p.u8(2), 0xa0, 'orientation must not overwrite activation key 2')
motion.setTriggerKeys(p, [9, 10, 255])
assert.deepEqual(motion.triggerKeys(p), [9, 10, 255])
assert.equal(p.u8(5), 0xa0, 'keys must not overwrite deadzone flag')
setWindow(p, 6, [50, 950, 100, 900])
assert.deepEqual([6, 8, 10, 12].map((i) => p.u16be(i)), [50, 950, 100, 900])
const saved = p.bytes.slice()
assert.throws(() => setWindow(p, 6, [950, 50, 0, 1000]))
assert.deepEqual(p.bytes, saved, 'invalid window must not partially mutate the packet')
setHair(p, 1, 10, 90)
assert.equal(p.u8(16), 0xa1, 'hair trigger preserves reserved bits')
setHair(p, 2, 10, 90)
assert.equal(p.u8(16), 0xa2)
const before = p.bytes.slice()
assert.throws(() => setHair(p, 1, 101, 10))
assert.deepEqual(p.bytes, before)
setHair(p, 1, 20, 5)
assert.equal(p.u8(17), 20, 'adaptive thresholds are independent')
assert.equal(p.u8(18), 5)
const points = [0, 64, 128, 191, 255].map((v) => ({ x: v, y: v }))
setCustomCurve(p, 17, points)
assert.equal(p.u8(15), 3)
assert.equal(p.bit(14, 0), true)
const curve = p.bytes.slice()
assert.throws(() => setCustomCurve(p, 17, points.map((v, i) => i === 2 ? { x: 64, y: 128 } : v)))
assert.deepEqual(p.bytes, curve)
const original = Uint8Array.from({ length: 1070 }, (_, i) => (i * 13) % 256)
original.fill(0, 0, 32)
const profile = parseProfile(original, 'G7ProCE')
setMotionActivation(profile.motion, 1, 3)
assert.equal(profile.motion[0].u8(0), 0)
assert.equal(profile.motion[1].u8(0), 3)
const encoded = serializeProfile(profile)
for (let i = 0; i < original.length; i++) if (i !== 988 && i !== 1029) assert.equal(encoded[i], original[i], `unrelated byte ${i}`)
assert.deepEqual(calibrateParts(0, 3, 1).slice(0, 5), [15, 254, 0, 3, 1])
assert.deepEqual(calibrateParts(1, 12).slice(0, 5), [15, 254, 1, 12, 0])
assert.throws(() => calibrateParts(1, 16, 1))
assert.throws(() => calibrateParts(3, 15))
const rawStick = new Packet(new Uint8Array(36).fill(0xa0))
const originalStick = rawStick.bytes.slice()
stick.applyRawLinear(rawStick)
assert.equal(stick.enabled(rawStick), true, 'raw-linear must never disable stick processing')
assert.equal(stick.squareGate(rawStick), true, 'raw shape matches Connect rawEnabled')
assert.equal(stick.isRawLinear(rawStick), true)
assert.deepEqual(stick.deadzone(rawStick), { begin: 0, end: 1000, beginAnti: 0, endAnti: 1000 })
assert.equal(rawStick.u8(12), 0, 'linear preset overrides old curve mode')
for (const i of [24, 25, 26, 28, 29, 30, 31, 32, 33, 34, 35]) assert.equal(rawStick.u8(i), originalStick[i], `mapping byte ${i} preserved`)
for (const i of [0, 1, 2, 11]) assert.equal(rawStick.u8(i) & 0xfe, originalStick[i] & 0xfe, 'reserved flag bits preserved')
stick.setEnabled(rawStick, false)
assert.equal(stick.isRawLinear(rawStick), false, 'old disabled-stick state is not called linear')
console.log('Trigger/gyro byte preservation, atomic validation and calibration command tests passed.')
